import type { Metadata } from "next";
import { cookies } from "next/headers";
import Script from "next/script";
import { Geist, Geist_Mono } from "next/font/google";
import LayoutWrapper from "./components/LayoutWrapper"; // ✅ IMPORTED
import { Toaster } from "react-hot-toast";
import { RouteProvider } from "./components/routeProvider";
import "@/styles/globals.css";
import { GlobalConstants } from "@/utils/global";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: GlobalConstants.APP_BASE_TITLE,
  description: "Generated by Usman",
};

const getAuthStatus = async () => {
  const sessionCookie = (await cookies()).get("authSession");

  if (sessionCookie) {
    try {
      const userData = JSON.parse(sessionCookie.value);
      // Return true only if the cookie exists AND the payload says authenticated
      return userData;
    } catch (e) {
      // console.error("Failed to parse auth cookie in layout:", e);
    }
  }
  return false; // Not authenticated or cookie invalid
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const useData = await getAuthStatus();

  return (
    <html lang="en" suppressHydrationWarning={true}>
      <head>
        <link
          href="https://fonts.googleapis.com/icon?family=Material+Icons"
          rel="stylesheet"
        />
      </head>
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
        suppressHydrationWarning={true}
      >
        {/* Hotjar Script */}
        <Script
          src="https://t.contentsquare.net/uxa/bedb577941075.js"
          strategy="afterInteractive"
        />

        {/* Smartlook Script */}
        <Script id="smartlook-init" strategy="afterInteractive">
          {`
            window.smartlook||(function(d) {
              var o=smartlook=function(){ o.api.push(arguments)},h=d.getElementsByTagName('head')[0];
              var c=d.createElement('script');o.api=new Array();c.async=true;c.type='text/javascript';
              c.charset='utf-8';c.src='https://web-sdk.smartlook.com/recorder.js';h.appendChild(c);
            })(document);
            smartlook('init', '4ad5b6cbf10f919af6767bc19918460094d18594', { region: 'eu' });
          `}
        </Script>

        <Toaster position="top-right" reverseOrder={false} />
        <RouteProvider>
          <LayoutWrapper useData={useData}>{children}</LayoutWrapper>
        </RouteProvider>
      </body>
    </html>
  );
}
